#!/usr/bin/env python3
"""Copies the panel's icons (web/src/components/Icon.vue) into the app, so both draw the
same glyphs: app/lib/ui/icons_gen.dart. Run it after changing an icon."""
import re
from pathlib import Path

root = Path(__file__).resolve().parent.parent
src = (root / "web/src/components/Icon.vue").read_text()


def block(name):
    body = src[src.index(f"const {name} = {{"):]
    body = body[: body.index("} as const")]
    out = {}
    for m in re.finditer(r"^\s*'?([a-z][a-z-]*)'?:\s*\n?\s*'([^']*)'", body, re.M):
        out[m.group(1)] = m.group(2)
    return out


stroked, filled = block("PATHS"), block("FILLED")
lines = [
    "// Generated by tools/gen-app-icons.py from web/src/components/Icon.vue. Do not edit.",
    "",
    "/// Stroke icons (24 x 24, stroke 2, round caps), like the panel.",
    "const strokeIcons = <String, String>{",
]
lines += [f"  '{k}': '{v}'," for k, v in stroked.items()]
lines += ["};", "", "/// Filled icons.", "const filledIcons = <String, String>{"]
lines += [f"  '{k}': '{v}'," for k, v in filled.items()]
lines += ["};", ""]
(root / "app/lib/ui/icons_gen.dart").write_text("\n".join(lines))
print(f"{len(stroked)} stroke and {len(filled)} filled icons")
