#!/usr/bin/env python3
"""Copies the panel's icons (web/src/components/Icon.vue) into the app, so both draw the
same glyphs: app/lib/ui/icons_gen.dart. Run it after changing an icon."""
import re
from pathlib import Path

root = Path(__file__).resolve().parent.parent
src = (root / "web/src/components/Icon.vue").read_text()


def block(name):
    body = src[src.index(f"const {name} = {{"):]
    body = body[: body.index("} as const")]
    out = {}
    for m in re.finditer(r"^\s*'?([a-z][a-z-]*)'?:\s*'([^']*)'", body, re.M):
        out[m.group(1)] = m.group(2)
    return out


symbols, small, brands = block("PATHS"), block("SMALL"), block("BRAND")
lines = [
    "// Generated by tools/gen-app-icons.py from web/src/components/Icon.vue. Do not edit.",
    "",
    "/// Official Material Symbols Rounded paths (960 x 960 grid, filled), like the panel.",
    "const symbolIcons = <String, String>{",
]
lines += [f"  '{k}': '{v}'," for k, v in symbols.items()]
lines += [
    "};",
    "",
    "/// Official glyphs the repository still draws on the legacy 24 x 24 grid, and the",
    "/// brand marks that Material Symbols does not cover.",
    "const grid24Icons = <String, String>{",
]
lines += [f"  '{k}': '{v}'," for k, v in {**small, **brands}.items()]
lines += ["};", ""]
(root / "app/lib/ui/icons_gen.dart").write_text("\n".join(lines))
print(f"{len(symbols)} symbols, {len(small)} legacy and {len(brands)} brand icons")
